print("Datos de un viaje en carro")
print("__________________________________________________________________________")
print("A continuación deberá ingresar la información requerida acerca de su viaje en carro")
modelo_carro=input("¿Cuál es el modelo del carro?: ")
placa=input("¿Cuál es la placa del carro?: ")
origen=input("¿Cuál es el lugar de origen del viaje?: ")
destino=input("¿Cuál es el lugar de destino del viaje?: ")
num_pasajeros=int(input("¿Cuántos pasajeros viajan?: "))
peajes=int(input("¿Cuántos peajes se pagan durante el viaje?: "))
costo_peaje=float(input("¿Cuál es el costo de cada peaje?: "))
vel_estimada=int(input("¿Cuál es la velocidad promedio del viaje en km/h?: "))
limite_velkm=80
distancia=int(input("¿Cuál es la distancia del viaje en km?: "))

print("__________________________________________________________________________")
print("Esta es la información del viaje en carro:")
print("Modelo del carro: ")
print(modelo_carro)
print("Placa del carro: ")
print(placa)
print("Lugar de origen: ")
print(origen)
print("Lugar de destino: ")
print(destino)
print("Número de pasajeros: ")
print(num_pasajeros)
print("Número de peajes: ")
print(peajes)
print("Costo de cada peaje: ")
print(costo_peaje)
total_peajes=peajes*costo_peaje
print("Costo total de todos los peajes pagados: ")
print(total_peajes)
print("Velocidad estimada: ")
print(vel_estimada)
if vel_estimada > limite_velkm:
    print("¡Atención! La velocidad estimada excede el límite de velocidad.")
else:
    print("La velocidad estimada está dentro del límite de velocidad.")
print("Distancia del viaje: ")
print(distancia)
tiempo_horas=distancia/vel_estimada
print("Tiempo estimado del viaje en horas: ")
print(tiempo_horas)